#!/usr/bin/env python3
"""Generate the UTF-8 -> GB18030 encoder table for the browser port.

musl's iconv (the Emscripten C library) supports GB18030 only as a SOURCE
encoding (legacy -> Unicode); iconv_open("GB18030", "UTF-8") fails, so the
port cannot rely on iconv to encode package-lookup names. This generator
derives the complete Unicode -> GB18030 mapping from Python's official
gb18030 codec (which implements the GB18030 standard) and emits:

  * the two-byte (GBK) mapping as a sorted codepoint table, and
  * the four-byte linear segments as (codepoint, linear-value) breakpoints.

Output: src/client153/platform/common/gb18030_encoder_table.h
"""

import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/client153/platform/common/gb18030_encoder_table.h'

MAX_CP = 0x110000


def gb_linear(enc: bytes) -> int:
    """Linear value of a 4-byte GB18030 sequence (standard formula)."""
    b1, b2, b3, b4 = enc
    return ((b1 - 0x81) * 10 + (b2 - 0x30)) * 1260 + (b3 - 0x81) * 10 + (b4 - 0x30)


def main() -> int:
    two_byte = []  # (codepoint, gb16)
    # The 4-byte range is linear in (codepoint - segment start) THROUGH
    # codepoints that have 2-byte encodings or none: the standard assigns
    # the 4-byte space continuously, so a segment breaks only when the
    # (linear - codepoint) delta changes.
    four_segments = []  # (codepoint_start, linear_start)
    prev_delta = None
    for cp in range(0x80, MAX_CP):
        try:
            enc = chr(cp).encode('gb18030')
        except UnicodeEncodeError:
            continue
        if len(enc) == 2:
            two_byte.append((cp, (enc[0] << 8) | enc[1]))
        elif len(enc) == 4:
            lin = gb_linear(enc)
            delta = lin - cp
            if delta != prev_delta:
                four_segments.append((cp, lin))
                prev_delta = delta
        else:
            raise SystemExit(f'unexpected encoding length for U+{cp:04X}: {enc.hex()}')

    lines = [
        '// GENERATED FILE - DO NOT EDIT.',
        '// Generated by tools/gen-gb18030-encoder.py from Python\'s official',
        '// gb18030 codec (the GB18030 standard mapping). Provenance: the',
        '// generator script is the source of truth; regenerate after any',
        '// change. Used by a_Utf8ToGb18030 (AAssist.cpp): musl iconv cannot',
        '// encode TO GB18030, so the port owns this encoder.',
        '#ifndef PW153_GB18030_ENCODER_TABLE_H',
        '#define PW153_GB18030_ENCODER_TABLE_H',
        '',
        '#include <cstdint>',
        '',
        'namespace pw153_gb18030 {',
        '',
        'struct TwoByteEntry { uint16_t codepoint; uint16_t gb; };',
        f'inline constexpr TwoByteEntry TWO_BYTE[{len(two_byte)}] = {{',
    ]
    for i in range(0, len(two_byte), 4):
        row = two_byte[i:i + 4]
        lines.append('  ' + ' '.join(f'{{0x{cp:04x}, 0x{gb:04x}}},' for cp, gb in row))
    lines.append('};')
    lines.append('')
    lines.append('// Four-byte sequences are linear in (codepoint - segment start) with')
    lines.append('// these standard breakpoints: linear = (b1-0x81)*12600+(b2-0x30)*1260')
    lines.append('// +(b3-0x81)*10+(b4-0x30); codepoint = start_cp + (linear - start_linear).')
    lines.append('struct FourByteSegment { uint32_t codepoint; uint32_t linear; };')
    lines.append(f'inline constexpr FourByteSegment FOUR_BYTE[{len(four_segments)}] = {{')
    for cp, lin in four_segments:
        lines.append(f'  {{0x{cp:04x}, 0x{lin:05x}}},')
    lines.append('};')
    lines.append('')
    lines.append('}  // namespace pw153_gb18030')
    lines.append('')
    lines.append('#endif  // PW153_GB18030_ENCODER_TABLE_H')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'two-byte entries: {len(two_byte)}')
    print(f'four-byte segments: {len(four_segments)}')
    for cp, lin in four_segments:
        print(f'  U+{cp:04X} <-> linear 0x{lin:05X}')
    print(f'wrote {OUT}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
