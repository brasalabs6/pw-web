/*	Create a ID base on specified string

	Return created ID.

	szStr: specified string.
*/
DWORD a_MakeIDFromString(const char* szStr)
{
	ASSERT(szStr);

	DWORD c = 0xffffffff; /* shift register contents */
	const BYTE* p = (const BYTE*)szStr;

	while (*p)
	{
		c = l_aCRC32Table[((int)c ^ (*p++)) & 0xff] ^ (c >> 8);
	};

	return c ^ 0xffffffffL;
}

/*	Create a ID base on specified string's lowercase version

	Return created ID.

	szStr: specified string.
*/
DWORD a_MakeIDFromLowString(const char* szStr)
{
	ASSERT(szStr);

	DWORD c = 0xffffffff; /* shift register contents */
	const BYTE* p = (const BYTE*)szStr;

	while (*p)
	{
		unsigned char ch = *p++;
		if (ch >= 'A' && ch <= 'Z')
			ch += 32;

		c = l_aCRC32Table[((int)c ^ (ch)) & 0xff] ^ (c >> 8);
	}

	return c ^ 0xffffffffL;
}

int a_Utf8ToGb18030(const char* szUtf8, char* szGb18030, int iGb18030Size)
{
	if (!szUtf8 || !szGb18030 || iGb18030Size <= 0) return 0;

	//	Fast path: pure ASCII needs no conversion (identical in both).
	bool bNeedsConversion = false;
	for (const unsigned char* p = (const unsigned char*)szUtf8; *p; ++p)
	{
		if (*p >= 0x80) { bNeedsConversion = true; break; }
	}
	if (!bNeedsConversion)
	{
		std::strncpy(szGb18030, szUtf8, iGb18030Size - 1);
		szGb18030[iGb18030Size - 1] = '\0';
		return (int)std::strlen(szGb18030);
	}

	//	Convert UTF-8 multi-byte sequences to GB18030 (the encoding the
	//	original .pck package indexes use). musl's iconv supports GB18030
	//	only as a SOURCE encoding (legacy -> Unicode), so the port owns a
	//	complete encoder built on the generated standard mapping table
	//	(tools/gen-gb18030-encoder.py).
	const unsigned char* in = (const unsigned char*)szUtf8;
	int out = 0;
	while (*in)
	{
		uint32_t cp;
		int seq;
		if (*in < 0x80) { cp = *in; seq = 1; }
		else if ((*in & 0xE0) == 0xC0) { cp = *in & 0x1F; seq = 2; }
		else if ((*in & 0xF0) == 0xE0) { cp = *in & 0x0F; seq = 3; }
		else if ((*in & 0xF8) == 0xF0) { cp = *in & 0x07; seq = 4; }
		else { szGb18030[0] = '\0'; return 0; }	//	invalid UTF-8
		for (int i = 1; i < seq; ++i)
		{
			if ((in[i] & 0xC0) != 0x80) { szGb18030[0] = '\0'; return 0; }
			cp = (cp << 6) | (in[i] & 0x3F);
		}
		//	Reject overlong encodings (multi-byte decoding below U+0080),
		//	surrogates and out-of-range values. Single-byte ASCII (seq 1)
		//	is legitimate and handled below.
		if ((seq > 1 && cp < 0x80) || cp > 0x10FFFF || (cp >= 0xD800 && cp <= 0xDFFF))
		{ szGb18030[0] = '\0'; return 0; }

		if (cp < 0x80)
		{
			if (out + 1 >= iGb18030Size) { szGb18030[0] = '\0'; return 0; }
			szGb18030[out++] = (char)cp;
		}
		else
		{
			//	Two-byte (GBK) range: binary search the generated table.
			constexpr int TWO_BYTE_COUNT = int(sizeof(pw153_gb18030::TWO_BYTE) / sizeof(pw153_gb18030::TWO_BYTE[0]));
			int lo = 0, hi = TWO_BYTE_COUNT - 1;
			int found = -1;
			while (lo <= hi)
			{
				const int mid = (lo + hi) / 2;
				const auto& e = pw153_gb18030::TWO_BYTE[mid];
				if (e.codepoint == cp) { found = mid; break; }
				if (e.codepoint < cp) lo = mid + 1; else hi = mid - 1;
			}
			if (found >= 0)
			{
				if (out + 2 >= iGb18030Size) { szGb18030[0] = '\0'; return 0; }
				const auto gb = pw153_gb18030::TWO_BYTE[found].gb;
				szGb18030[out++] = (char)(gb >> 8);
				szGb18030[out++] = (char)(gb & 0xFF);
			}
			else
			{
				//	Four-byte range: linear in (cp - segment start).
				constexpr int FOUR_BYTE_COUNT = int(sizeof(pw153_gb18030::FOUR_BYTE) / sizeof(pw153_gb18030::FOUR_BYTE[0]));
				int lo2 = 0, hi2 = FOUR_BYTE_COUNT - 1, seg = -1;
				while (lo2 <= hi2)
				{
					const int mid = (lo2 + hi2) / 2;
					if (pw153_gb18030::FOUR_BYTE[mid].codepoint <= cp) { seg = mid; lo2 = mid + 1; }
					else hi2 = mid - 1;
				}
				if (seg < 0) { szGb18030[0] = '\0'; return 0; }
				const uint32_t lin = pw153_gb18030::FOUR_BYTE[seg].linear + (cp - pw153_gb18030::FOUR_BYTE[seg].codepoint);
				if (out + 4 >= iGb18030Size) { szGb18030[0] = '\0'; return 0; }
				szGb18030[out++] = (char)(0x81 + lin / 12600);
				szGb18030[out++] = (char)(0x30 + (lin % 12600) / 1260);
				szGb18030[out++] = (char)(0x81 + (lin % 1260) / 10);
				szGb18030[out++] = (char)(0x30 + lin % 10);
			}
		}
		in += seq;
	}
	szGb18030[out] = '\0';
	return out;
}

int a_Gb18030ToUtf8(const char* szGb18030, char* szUtf8, int iUtf8Size)
{
	if (!szGb18030 || !szUtf8 || iUtf8Size <= 0) return 0;

	//	musl's iconv supports GB18030 as a SOURCE encoding, so this
	//	direction needs no generated table. ASCII passes through unchanged.
	iconv_t cd = iconv_open("UTF-8", "GB18030");
	if (cd == (iconv_t)-1) return 0;

	size_t inLen = std::strlen(szGb18030);
	size_t outLen = iUtf8Size - 1;
	char* inPtr = const_cast<char*>(szGb18030);
	char* outPtr = szUtf8;

	const size_t result = iconv(cd, &inPtr, &inLen, &outPtr, &outLen);
	iconv_close(cd);

	if (result == (size_t)-1)
	{
		szUtf8[0] = '\0';
		return 0;
	}
	*outPtr = '\0';
	return (int)(outPtr - szUtf8);
}

int a_MixedPathToGb18030(const char* szPath, char* szGb18030, int iGb18030Size)
{
	if (!szPath || !szGb18030 || iGb18030Size <= 0) return 0;

	int out = 0;
	const char* segment = szPath;
	for (const char* p = szPath; ; ++p)
	{
		if (*p != '\\' && *p != '/' && *p != '\0')
			continue;
		//	Segment [segment, p): convert when it is valid UTF-8 carrying
		//	non-ASCII bytes; keep the raw bytes otherwise (already GB18030
		//	or pure ASCII). The separator itself is copied verbatim.
		//	NOTE: short GB18030 sequences can also be valid UTF-8, so this
		//	heuristic can corrupt ambiguous segments; the PCK resolver treats
		//	its output as one candidate among several and lets the index
		//	decide (a_LastSegmentToGb18030 covers the dominant pattern).
		const size_t len = (size_t)(p - segment);
		if (len >= MAX_PATH) { szGb18030[0] = '\0'; return 0; }
		char segmentBuf[MAX_PATH];
		std::memcpy(segmentBuf, segment, len);
		segmentBuf[len] = '\0';

		bool asciiOnly = true;
		bool validUtf8 = true;
		for (size_t i = 0; i < len; ++i)
		{
			const unsigned char byte = (unsigned char)segmentBuf[i];
			if (byte >= 0x80) { asciiOnly = false; }
		}
		if (!asciiOnly)
		{
			//	Strict UTF-8 validation over the segment bytes.
			for (size_t i = 0; i < len && validUtf8; )
			{
				const unsigned char lead = (unsigned char)segmentBuf[i];
				int seq = 0;
				if (lead < 0x80) seq = 1;
				else if ((lead & 0xE0) == 0xC0) seq = 2;
				else if ((lead & 0xF0) == 0xE0) seq = 3;
				else if ((lead & 0xF8) == 0xF0) seq = 4;
				else validUtf8 = false;
				for (int k = 1; k < seq && validUtf8; ++k)
				{
					if (i + k >= len || ((unsigned char)segmentBuf[i + k] & 0xC0) != 0x80)
						validUtf8 = false;
				}
				i += seq > 0 ? seq : 1;
			}
		}
		if (!asciiOnly && validUtf8)
		{
			char converted[MAX_PATH];
			const int convertedLen = a_Utf8ToGb18030(segmentBuf, converted, MAX_PATH);
			if (convertedLen > 0 && out + convertedLen < iGb18030Size)
			{
				std::memcpy(szGb18030 + out, converted, convertedLen);
				out += convertedLen;
			}
			else { szGb18030[0] = '\0'; return 0; }
		}
		else
		{
			if (out + (int)len + 1 > iGb18030Size) { szGb18030[0] = '\0'; return 0; }
			std::memcpy(szGb18030 + out, segmentBuf, len);
			out += (int)len;
		}
		if (*p == '\0')
			break;
		if (out + 1 >= iGb18030Size) { szGb18030[0] = '\0'; return 0; }
		szGb18030[out++] = *p;
		segment = p + 1;
	}
	szGb18030[out] = '\0';
	return out;
}

int a_LastSegmentToGb18030(const char* szPath, char* szGb18030, int iGb18030Size)
{
	if (!szPath || !szGb18030 || iGb18030Size <= 0) return 0;

	//	The dominant mixed pattern: legacy GB18030 directories from data
	//	files plus a UTF-8 final segment from the normalized asset reads.
	//	Convert only the final segment; keep everything else byte-exact.
	const char* lastSlash = szPath;
	for (const char* p = szPath; *p; ++p)
		if (*p == '\\' || *p == '/')
			lastSlash = p + 1;

	const int headLen = (int)(lastSlash - szPath);
	if (headLen >= iGb18030Size) { szGb18030[0] = '\0'; return 0; }
	std::memcpy(szGb18030, szPath, headLen);

	char converted[MAX_PATH];
	const int convertedLen = a_Utf8ToGb18030(lastSlash, converted, MAX_PATH);
	if (convertedLen <= 0 || headLen + convertedLen >= iGb18030Size)
	{
		szGb18030[0] = '\0';
		return 0;
	}
	std::memcpy(szGb18030 + headLen, converted, convertedLen);
	szGb18030[headLen + convertedLen] = '\0';
	return headLen + convertedLen;
}

int a_RunMixedToGb18030(const char* szPath, char* szGb18030, int iGb18030Size)
{
	if (!szPath || !szGb18030 || iGb18030Size <= 0) return 0;

	int out = 0;
	const char* p = szPath;
	while (*p)
	{
		//	Try a maximal strict UTF-8 sequence at p. Only 3/4-byte leads
		//	are attempted: the CJK the UTF-8-encoded sources carry. The
		//	2-byte leads are ambiguous with GB18030 pairs and stay raw.
		const unsigned char lead = (unsigned char)*p;
		int seq = 0;
		if (lead >= 0xE0 && lead <= 0xEF) seq = 3;
		else if (lead >= 0xF0 && lead <= 0xF7) seq = 4;
		if (seq)
		{
			bool valid = true;
			for (int k = 1; k < seq && valid; ++k)
				if (((unsigned char)p[k] & 0xC0) != 0x80) valid = false;
			if (valid)
			{
				//	Extend over consecutive valid sequences so the run
				//	converts in one a_Utf8ToGb18030 call.
				const char* runEnd = p + seq;
				while (*runEnd)
				{
					const unsigned char l2 = (unsigned char)*runEnd;
					int s2 = 0;
					if (l2 >= 0xE0 && l2 <= 0xEF) s2 = 3;
					else if (l2 >= 0xF0 && l2 <= 0xF7) s2 = 4;
					bool v2 = s2 > 0;
					for (int k = 1; k < s2 && v2; ++k)
						if (((unsigned char)runEnd[k] & 0xC0) != 0x80) v2 = false;
					if (!v2) break;
					runEnd += s2;
				}
				const int runLen = (int)(runEnd - p);
				if (runLen < MAX_PATH)
				{
					char runBuf[MAX_PATH];
					std::memcpy(runBuf, p, (size_t)runLen);
					runBuf[runLen] = '\0';
					char converted[MAX_PATH];
					const int convertedLen = a_Utf8ToGb18030(runBuf, converted, MAX_PATH);
					if (convertedLen > 0 && out + convertedLen < iGb18030Size)
					{
						std::memcpy(szGb18030 + out, converted, (size_t)convertedLen);
						out += convertedLen;
						p = runEnd;
						continue;
					}
				}
			}
		}
		if (out + 1 >= iGb18030Size) { szGb18030[0] = '\0'; return 0; }
		szGb18030[out++] = *p++;
	}
	szGb18030[out] = '\0';
	return out;
}

int a_Gb18030ToWide(const char* szGb18030, int iGbLen, wchar_t* szWide, int iWideSize)
{
	if (!szGb18030 || iGbLen <= 0) return 0;

	//	Size query (szWide == nullptr): report the wide length the caller
	//	must allocate. GB18030 yields at most one UTF-16 unit per input byte
	//	(1- and 2-byte sequences give one unit; 4-byte sequences give one
	//	unit or a surrogate pair), so iGbLen + 1 units always suffice.
	if (!szWide)
	{
		std::vector<wchar_t> count(static_cast<size_t>(iGbLen) + 1);
		return a_Gb18030ToWide(szGb18030, iGbLen, count.data(), static_cast<int>(count.size()));
	}
	if (iWideSize <= 0) return 0;

	iconv_t cd = iconv_open("UTF-16LE", "GB18030");
	if (cd == (iconv_t)-1) return 0;

	size_t inLen = iGbLen;
	size_t outLen = iWideSize * sizeof(wchar_t);
	char* inPtr = const_cast<char*>(szGb18030);
	char* outPtr = reinterpret_cast<char*>(szWide);

	size_t result = iconv(cd, &inPtr, &inLen, &outPtr, &outLen);
	iconv_close(cd);

	if (result == (size_t)-1) return 0;
	return (int)((reinterpret_cast<char*>(outPtr) - reinterpret_cast<char*>(szWide)) / sizeof(wchar_t));
}

/*	Get string after specified tag string

	szBuffer: buffer will be searched.
	szTag: tag string.
	szResult: buffer used to store result string.
*/
bool a_GetStringAfter(const char* szBuffer, const char* szTag, char* szResult)
{
	szResult[0] = '\0';

	const char* pch = strstr(szBuffer, szTag);
	if (pch != szBuffer)
		return false;

	pch += strlen(szTag);
	strcpy(szResult, pch);

	return true;
}

//	Conversion between narrow (UTF-8) and wide (UTF-16) strings: the strict
//	platform conversions back these; malformed input yields an empty result
//	and the code-page argument stays unused (documented port divergence).
AWString AS2WC(const char* szAnsi)
{
	AWString result;
	if (!szAnsi)
		return result;
	std::wstring out;
	if (pw153::platform::utf8_to_utf16(szAnsi, out))
		result = AWString(out.c_str(), (int)out.size());
	return result;
}

